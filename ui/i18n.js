// The value for a key, in the current language, falling back to English rather
// than to nothing: a missing translation should read oddly, not vanish.
function entry(key) {
  const here = STRINGS[locale]?.[key];
  return here === undefined ? STRINGS.en[key] : here;
}

// One string for `key`, with {name} placeholders filled from `args`. A value
// written as an object is a counted phrase, and `args.n` picks the plural form.
function t(key, args = {}) {
  let value = entry(key);
  if (value === undefined) return key;
  if (typeof value === "object") {
    const form = plurals.select(Number(args.n) || 0);
    value = value[form] ?? value.other ?? value.many ?? value.one ?? "";
  }
  // Numbers arrive as numbers and are written out for the current locale. A
  // whole number keeps its shape; anything else gets one decimal.
  return String(value).replace(/\{(\w+)\}/g, (whole, name) => {
    if (!(name in args)) return whole;
    const filling = args[name];
    if (typeof filling !== "number") return String(filling);
    return Number.isInteger(filling) ? num(filling) : num(filling, 1);
  });
}

// A number as this language writes it: 5.9 in English, 5,9 in French.
function num(value, digits = 0) {
  return new Intl.NumberFormat(locale, {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(Number(value) || 0);
}

// A date as this language writes it. 03.09 and 09/03 are the same day to two
// readers who would each misread the other, so neither is written by hand.
function date(iso) {
  const parsed = new Date(iso);
  if (Number.isNaN(parsed.getTime())) return String(iso);
  return new Intl.DateTimeFormat(locale, { dateStyle: "medium" }).format(parsed);
}

// Arguments that are counts, and the phrase each one becomes. A count has to
// agree with its noun in most of these languages, so the phrase is built first
// and the sentence around it.
const COUNTED = {
  articles: "count.articles",
  summaries: "count.summaries",
  recordings: "count.recordings",
};

// One `Msg` from Rust: a code and the values that go in it. A code with no
// sentence here falls back to the detail that came with it, then to the code.
function say(part) {
  const args = { ...(part.args ?? {}) };
  for (const [name, key] of Object.entries(COUNTED)) {
    if (typeof args[name] === "number") args[name] = t(key, { n: args[name] });
  }
  // One more convention crosses the boundary: an argument called `cutoff` is a
  // date, and 03.09 means two different days to two of these readers.
  if ("cutoff" in args) args.cutoff = date(args.cutoff);
  for (const key of [part.code, `error.${part.code}`]) {
    if (entry(key) !== undefined) return t(key, args);
  }
  return args.detail ? String(args.detail) : part.code;
}

// The list of statements a finished job reports, joined the way this language
// joins things.
function joinParts(parts) {
  return parts.map(say).join(t("misc.list_sep"));
}

// A word for one of Rust's own names: a source kind, a verdict. A name with no
// word here shows itself rather than a dictionary key.
function labelOf(prefix, value) {
  const key = `${prefix}.${value}`;
  return entry(key) === undefined ? String(value) : t(key);
}

// Read the English out of the page, once, before anything overwrites it.
function harvestEnglish() {
  for (const [attribute, key] of ATTRIBUTES) {
    for (const node of document.querySelectorAll(`[${key}]`)) {
      const name = node.getAttribute(key);
      if (name in STRINGS.en) continue;
      STRINGS.en[name] = attribute === null ? node.innerHTML.trim() : node.getAttribute(attribute);
    }
  }
}

// Which attribute each kind of key writes to. `null` means the node's content.
const ATTRIBUTES = [
  [null, "data-i18n"],
  ["placeholder", "data-i18n-placeholder"],
  ["title", "data-i18n-title"],
  ["aria-label", "data-i18n-aria"],
];

// Write every marked node in the current language.
function applyStatic() {
  for (const [attribute, key] of ATTRIBUTES) {
    for (const node of document.querySelectorAll(`[${key}]`)) {
      const text = t(node.getAttribute(key));
      if (attribute === null) {
        node.innerHTML = text;
      } else {
        node.setAttribute(attribute, text);
        // The placeholder is also stashed for the focus/blur rule that clears
        // it while the field is in use; that copy has to move languages too.
        if (attribute === "placeholder") node.dataset.hint = text;
      }
    }
  }
}

// Switch the window to `tag`, which must be one the settings offer.
function setLocale(tag) {
  locale = STRINGS[tag] ? tag : "en";
  plurals = new Intl.PluralRules(locale);
  document.documentElement.lang = locale;
  applyStatic();
}

harvestEnglish();
